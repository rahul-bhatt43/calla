--[[
  Atomic match-or-enqueue.

  The whole point of doing this in Lua is that Redis runs the script with the
  server single-threaded and uninterrupted. The obvious alternative -- ZRANGE
  from Node, pick a partner, then ZREM -- has a fatal race: two signaling nodes
  can read the same candidate in the gap between the read and the remove, and
  both will believe they own them. The victim gets two simultaneous matches and
  one of the two peers waits forever on an offer that never arrives.

  Either this script hands back a fully-committed pair, or it enqueues the
  caller. There is no state in between that another node can observe.

  Keys are built dynamically, which is Cluster-incompatible by design: matching
  requires cross-slot visibility over the whole queue, so this deployment keeps
  one Redis per region rather than sharding.

  ARGV
    1  mode           'video' | 'text'
    2  selfId
    3  nowMs
    4  scanLimit      max queue entries to inspect
    5  roomId         pre-generated by the caller (Lua has no CSPRNG)
    6  lang
    7  country        '' when unknown
    8  interests      comma-separated
    9  tier           'interest' | 'language' | 'global'
    10 blocked        comma-separated user ids
    11 nodeId         which signaling process owns this socket
    12 displayName
    13 isGuest        '1' | '0'
    14 recentTtl      seconds
    15 recentLimit
    16 joinedAtMs     preserved across tier widening so waiting isn't punished
--]]

local mode        = ARGV[1]
local selfId      = ARGV[2]
local nowMs       = tonumber(ARGV[3])
local scanLimit   = tonumber(ARGV[4])
local roomId      = ARGV[5]
local selfLang    = ARGV[6]
local selfCountry = ARGV[7]
local interestCsv = ARGV[8]
local selfTier    = ARGV[9]
local blockedCsv  = ARGV[10]
local selfNode    = ARGV[11]
local selfName    = ARGV[12]
local selfGuest   = ARGV[13]
local recentTtl   = tonumber(ARGV[14])
local recentLimit = tonumber(ARGV[15])
local joinedAt    = tonumber(ARGV[16])

local qKey = 'q:' .. mode

-- ---------------------------------------------------------------- helpers --

local function splitSet(csv)
  local set = {}
  if csv and #csv > 0 then
    for token in string.gmatch(csv, '([^,]+)') do set[token] = true end
  end
  return set
end

local function hgetallMap(key)
  local flat = redis.call('HGETALL', key)
  if #flat == 0 then return nil end
  local map = {}
  for i = 1, #flat, 2 do map[flat[i]] = flat[i + 1] end
  return map
end

local function dropFromQueue(id)
  redis.call('ZREM', qKey, id)
  redis.call('DEL', 'u:' .. id)
end

local selfInterests = splitSet(interestCsv)
local selfBlocked   = splitSet(blockedCsv)

-- ------------------------------------------------------------ candidates --

-- Oldest first, so the longest-waiting users are always considered.
local candidates = redis.call('ZRANGE', qKey, 0, scanLimit - 1)

local bestId, bestScore, bestProfile = nil, -1, nil

for i = 1, #candidates do
  local candId = candidates[i]

  repeat
    if candId == selfId then break end

    -- Lazy reaping. A node that crashes mid-session leaves its users in the
    -- queue; their heartbeat key expires and they get cleaned up here, on the
    -- next scan that touches them. No separate sweeper process to operate.
    if redis.call('EXISTS', 'alive:' .. candId) == 0 then
      dropFromQueue(candId)
      break
    end

    local p = hgetallMap('u:' .. candId)
    if not p then
      redis.call('ZREM', qKey, candId)
      break
    end

    -- Blocks are enforced in both directions: being blocked has to be as
    -- effective as blocking, or the block is trivially defeated by re-queueing.
    if selfBlocked[candId] then break end
    if splitSet(p['blocked'] or '')[selfId] then break end

    -- Don't immediately re-pair two people who just skipped each other.
    if redis.call('ZSCORE', 'recent:' .. selfId, candId) then break end

    local shared = 0
    for token in string.gmatch(p['interests'] or '', '([^,]+)') do
      if selfInterests[token] then shared = shared + 1 end
    end

    local langMatch    = (p['lang'] == selfLang)
    local countryMatch = (selfCountry ~= '' and p['country'] == selfCountry)
    local candTier     = p['tier'] or 'global'

    -- Tier constraints are checked symmetrically. Honouring only the caller's
    -- tier would let someone who just joined yank a picky user out of their
    -- interest-matching window and hand them an unrelated partner.
    local ok = true
    if (selfTier == 'interest' or candTier == 'interest') and shared == 0 then ok = false end
    if ok and (selfTier == 'language' or candTier == 'language') and not langMatch then ok = false end
    if not ok then break end

    -- Interest overlap dominates; a seconds-of-waiting term (capped at 120)
    -- keeps the queue fair so a niche user is never starved by a steady stream
    -- of better-matching newcomers.
    local waitedS = math.min((nowMs - tonumber(p['joinedAt'] or nowMs)) / 1000, 120)
    local score = shared * 1000
    if langMatch then score = score + 200 end
    if countryMatch then score = score + 50 end
    score = score + waitedS

    if score > bestScore then
      bestScore, bestId, bestProfile = score, candId, p
    end
  until true
end

-- ---------------------------------------------------------------- commit --

if bestId then
  redis.call('ZREM', qKey, bestId)
  redis.call('ZREM', qKey, selfId)
  redis.call('DEL', 'u:' .. bestId, 'u:' .. selfId)

  redis.call('HSET', 'room:' .. roomId,
    'a', selfId, 'aNode', selfNode,
    'b', bestId, 'bNode', bestProfile['node'] or '',
    'mode', mode,
    'state', 'proposed',
    'acks', 0,
    'createdAt', nowMs)
  -- Rooms are ephemeral; the TTL is a backstop against leaking a hash when both
  -- peers vanish before either sends a teardown.
  redis.call('EXPIRE', 'room:' .. roomId, 3600)

  for _, pair in ipairs({ { selfId, bestId }, { bestId, selfId } }) do
    local key = 'recent:' .. pair[1]
    redis.call('ZADD', key, nowMs, pair[2])
    redis.call('ZREMRANGEBYRANK', key, 0, -(recentLimit + 1))
    redis.call('EXPIRE', key, recentTtl)
  end

  return {
    'matched',
    roomId,
    bestId,
    bestProfile['node'] or '',
    bestProfile['name'] or 'Stranger',
    bestProfile['guest'] or '1',
    bestProfile['country'] or '',
    bestProfile['lang'] or '',
    bestProfile['interests'] or '',
  }
end

-- No partner available: take a place in the queue instead.
redis.call('HSET', 'u:' .. selfId,
  'lang', selfLang,
  'country', selfCountry,
  'interests', interestCsv,
  'tier', selfTier,
  'blocked', blockedCsv,
  'node', selfNode,
  'name', selfName,
  'guest', selfGuest,
  'joinedAt', joinedAt)
redis.call('EXPIRE', 'u:' .. selfId, 300)
redis.call('ZADD', qKey, joinedAt, selfId)

return { 'queued', tostring(redis.call('ZCARD', qKey)) }
